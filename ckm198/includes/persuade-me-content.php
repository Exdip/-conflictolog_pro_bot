 * 0.3.23.134 stored the marker as question_stage=mechanic, while the shared room
 * preflight intentionally counts only active main questions. The four-round show
 * does not display this marker; it exists solely to satisfy the common room/revision
 * contract. Keep one active main marker in the current revision so old templates
 * launch without requiring the organizer to resave them.
 */
function ckm_quiz_pro_persuade_me_repair_contract_questions(): void {
    static $done=false;
    if($done) return;
    $done=true;
    if(!function_exists('ckm_quiz_pro_table')) return;
    global $wpdb;
    $qz=ckm_quiz_pro_table('quizzes');
    $qq=ckm_quiz_pro_table('questions');
    $rr=ckm_quiz_pro_table('rounds');
    if((string)$wpdb->get_var($wpdb->prepare('SHOW TABLES LIKE %s',$qz))!==$qz) return;
    if((string)$wpdb->get_var($wpdb->prepare('SHOW TABLES LIKE %s',$qq))!==$qq) return;
    if((string)$wpdb->get_var($wpdb->prepare('SHOW TABLES LIKE %s',$rr))!==$rr) return;

    $quizzes=$wpdb->get_results("SELECT id,current_revision,format_settings_json FROM {$qz} WHERE format_key='negotiation_duel'",ARRAY_A) ?: [];
    $now=current_time('mysql');
    foreach($quizzes as $quiz){
        $settings=json_decode((string)($quiz['format_settings_json']??''),true) ?: [];
        if((string)($settings['negotiationMode']??'')!=='communicate') continue;
        $quizId=(int)$quiz['id'];
        $revision=max(1,(int)$quiz['current_revision']);
        if($quizId<1) continue;
        $mainCount=(int)$wpdb->get_var($wpdb->prepare(
            "SELECT COUNT(*) FROM {$qq} WHERE quiz_id=%d AND quiz_revision=%d AND status='active' AND COALESCE(question_stage,'main')='main'",
            $quizId,$revision
        ));
        if($mainCount>0) continue;

        $roundId=(int)$wpdb->get_var($wpdb->prepare(
            "SELECT id FROM {$rr} WHERE quiz_id=%d AND quiz_revision=%d AND status='active' ORDER BY position ASC,id ASC LIMIT 1",
            $quizId,$revision
        ));
        if($roundId<1){
            $ok=$wpdb->insert($rr,[
                'quiz_id'=>$quizId,'quiz_revision'=>$revision,'round_key'=>'round-1','position'=>1,
                'title'=>'Переговори другого','round_type'=>'negotiation','rules_json'=>'{}','settings_json'=>'{}',
                'status'=>'active','created_at'=>$now,'updated_at'=>$now,
            ]);
            if($ok===false) continue;
            $roundId=(int)$wpdb->insert_id;
        }

        $markerId=(int)$wpdb->get_var($wpdb->prepare(
            "SELECT id FROM {$qq} WHERE quiz_id=%d AND quiz_revision=%d AND question_key=%s ORDER BY id ASC LIMIT 1",
            $quizId,$revision,'persuade-me-contract'
        ));
        $marker=[
            'position'=>1,'round_no'=>1,'round_title'=>'Переговори другого','round_id'=>$roundId,
            'question_stage'=>'main','question_type'=>'text','question_text'=>'Переговори другого — четырёхраундовая механика',
            'options_json'=>'[]','correct_answers_json'=>'[]','numeric_tolerance'=>0,'points'=>1,'time_limit_seconds'=>90,
            'scoring_rule_json'=>wp_json_encode(['runtime'=>'persuade_me_v1','contentInFormatSettings'=>true],JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES),
            'explanation'=>'Технический маркер общей игровой механики. Игрокам не показывается.','host_script'=>'',
            'media_url'=>'','media_type'=>'','media_start_seconds'=>0,'media_end_seconds'=>0,'status'=>'active',
            'updated_at'=>$now,
        ];
        if($markerId>0){
            $wpdb->update($qq,$marker,['id'=>$markerId]);
        } else {
            $marker['quiz_id']=$quizId;
            $marker['quiz_revision']=$revision;
            $marker['question_key']='persuade-me-contract';
            $marker['created_by_user_id']=0;
            $marker['created_at']=$now;
            $wpdb->insert($qq,$marker);
        }
    }
}
add_action('init','ckm_quiz_pro_persuade_me_repair_contract_questions',25);
