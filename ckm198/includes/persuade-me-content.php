function ckm_quiz_pro_persuade_me_clean_text($value, string $fallback=''): string {
    $value=is_scalar($value)?(string)$value:'';
    $value=function_exists('wp_unslash')?wp_unslash($value):$value;
    $value=function_exists('sanitize_textarea_field')?sanitize_textarea_field($value):trim(strip_tags($value));
    $value=trim($value);
    return $value!==''?$value:$fallback;
}

function ckm_quiz_pro_persuade_me_starter_role($value,string $fallback): string {
    $role=is_scalar($value)?strtolower(trim((string)$value)):'';
    if(function_exists('sanitize_key'))$role=sanitize_key($role);else $role=preg_replace('/[^a-z0-9_\-]/','',$role);
    return in_array($role,['speaker','opponent'],true)?$role:$fallback;
}

function ckm_quiz_pro_persuade_me_normalize_content($raw): array {
    $def=ckm_quiz_pro_persuade_me_default_content();
    if(!is_array($raw)) $raw=[];
    $out=$def;
    $out['version']=1;
    $r1=is_array($raw['round1']??null)?$raw['round1']:[];
    $out['round1']['observerBrief']=ckm_quiz_pro_persuade_me_clean_text($r1['observerBrief']??'', $def['round1']['observerBrief']);
    $cases=is_array($r1['cases']??null)?array_values($r1['cases']):[];
    for($i=0;$i<3;$i++){
        $row=is_array($cases[$i]??null)?$cases[$i]:[];$d=$def['round1']['cases'][$i];
        foreach(['situation','speaker','opponent'] as $k)$out['round1']['cases'][$i][$k]=ckm_quiz_pro_persuade_me_clean_text($row[$k]??'', $d[$k]);
        $out['round1']['cases'][$i]['starterRole']=ckm_quiz_pro_persuade_me_starter_role($row['starterRole']??($d['starterRole']??'opponent'),'opponent');
    }
    $r2=is_array($raw['round2']??null)?$raw['round2']:[];
    $out['round2']['situation']=ckm_quiz_pro_persuade_me_clean_text($r2['situation']??'', $def['round2']['situation']);
    $out['round2']['partnerBrief']=ckm_quiz_pro_persuade_me_clean_text($r2['partnerBrief']??'', $def['round2']['partnerBrief']);
    $out['round2']['starterRole']=ckm_quiz_pro_persuade_me_starter_role($r2['starterRole']??($def['round2']['starterRole']??'speaker'),'speaker');
    $tasks=is_array($r2['tasks']??null)?array_values($r2['tasks']):[];
    for($i=0;$i<3;$i++){
        $row=is_array($tasks[$i]??null)?array_values($tasks[$i]):[];
        for($j=0;$j<3;$j++)$out['round2']['tasks'][$i][$j]=ckm_quiz_pro_persuade_me_clean_text($row[$j]??'', $def['round2']['tasks'][$i][$j]);
    }
    $r3=is_array($raw['round3']??null)?$raw['round3']:[];
    $out['round3']['answerBrief']=ckm_quiz_pro_persuade_me_clean_text($r3['answerBrief']??'', $def['round3']['answerBrief']);
    $out['round3']['observerBrief']=ckm_quiz_pro_persuade_me_clean_text($r3['observerBrief']??'', $def['round3']['observerBrief']);
    $questions=is_array($r3['questions']??null)?array_values($r3['questions']):[];
    for($i=0;$i<3;$i++){
        $row=is_array($questions[$i]??null)?array_values($questions[$i]):[];
        for($j=0;$j<3;$j++)$out['round3']['questions'][$i][$j]=ckm_quiz_pro_persuade_me_clean_text($row[$j]??'', $def['round3']['questions'][$i][$j]);
    }
    $r4=is_array($raw['round4']??null)?$raw['round4']:[];
    $out['round4']['checkerBrief']=ckm_quiz_pro_persuade_me_clean_text($r4['checkerBrief']??'', $def['round4']['checkerBrief']);
    $dossiers=is_array($r4['dossiers']??null)?array_values($r4['dossiers']):[];
    for($i=0;$i<3;$i++){
        $row=is_array($dossiers[$i]??null)?$dossiers[$i]:[];$d=$def['round4']['dossiers'][$i];
        $out['round4']['dossiers'][$i]['title']=ckm_quiz_pro_persuade_me_clean_text($row['title']??'', $d['title']);
        $factsRaw=$row['facts']??($row['facts_text']??[]);
        if(is_string($factsRaw))$factsRaw=preg_split('/[\r\n]+/u',$factsRaw)?:[];
        if(!is_array($factsRaw))$factsRaw=[];$facts=array_values(array_filter(array_map(static fn($x)=>ckm_quiz_pro_persuade_me_clean_text($x,''),$factsRaw),static fn($x)=>$x!==''));
        for($j=0;$j<5;$j++)$out['round4']['dossiers'][$i]['facts'][$j]=$facts[$j]??$d['facts'][$j];
        $out['round4']['dossiers'][$i]['distortion']=ckm_quiz_pro_persuade_me_clean_text($row['distortion']??'', $d['distortion']);
    }
    return $out;
}

function ckm_quiz_pro_persuade_me_content_from_quiz(array $quiz): array {
    $settings=json_decode((string)($quiz['format_settings_json']??''),true);if(!is_array($settings))$settings=[];
    return ckm_quiz_pro_persuade_me_normalize_content($settings['persuadeMeContent']??null);
}
function ckm_quiz_pro_persuade_me_content_from_game(array $game): array {
    $settings=function_exists('ckm_quiz_json_decode')?ckm_quiz_json_decode((string)($game['format_settings_snapshot_json']??'')):json_decode((string)($game['format_settings_snapshot_json']??''),true);
    if(!is_array($settings))$settings=[];
    return ckm_quiz_pro_persuade_me_normalize_content($settings['persuadeMeContent']??null);
}
function ckm_quiz_pro_persuade_me_content_from_post($raw, $fallback=null): array {
    if(!is_array($raw))return ckm_quiz_pro_persuade_me_normalize_content($fallback);
    return ckm_quiz_pro_persuade_me_normalize_content($raw);
}

